def _pages(label: str = "Páginas", default: str = "", **kwargs) -> Text:
    return Text("pages", label, default, placeholder="Todas (ex.: 1-3, 5, 8-)", **kwargs)


def _paper(default: str = "A4", extra: Tuple[Tuple[str, str], ...] = ()) -> Choice:
    return Choice("paper", "Tamanho do papel", default, choices=PAPER_CHOICES + extra)


