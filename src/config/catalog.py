@lru_cache(maxsize=1)
def all_tools() -> Tuple[ToolSpec, ...]:
    return CREATE + ORGANIZE + EDIT + OPTIMIZE + SECURITY + VIEW + TO_PDF + FROM_PDF


@lru_cache(maxsize=1)
def tools_by_id() -> Dict[str, ToolSpec]:
    tools = all_tools()
    index = {tool.id: tool for tool in tools}
    if len(index) != len(tools):
        raise ValueError("IDs de ferramentas duplicados no catálogo.")
    return index
